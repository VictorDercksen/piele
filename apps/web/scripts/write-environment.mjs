// Writes src/environments/environment.ts from Vercel environment variables, so each
// Vercel environment (Preview for staging, Production for master) gets its own browser
// config. Only browser-safe values belong here. Runs on Vercel builds only.
import { writeFileSync } from 'node:fs';

if (!process.env.VERCEL) {
  console.log('Not a Vercel build: keeping src/environments/environment.ts.');
  process.exit(0);
}

const required = ['PIELE_API_URL', 'PIELE_SUPABASE_URL', 'PIELE_SUPABASE_PUBLISHABLE_KEY'];
const missing = required.filter((name) => !process.env[name]);
if (missing.length) {
  console.error(`Missing Vercel environment variables: ${missing.join(', ')}`);
  process.exit(1);
}

// Production never shows sample records and only talks to an HTTPS API.
if (process.env.VERCEL_ENV === 'production') {
  const problems = [];
  if (process.env.PIELE_SAMPLE_LEAGUE_DATA === 'true')
    problems.push('PIELE_SAMPLE_LEAGUE_DATA must not be true');
  if (!process.env.PIELE_API_URL.startsWith('https://'))
    problems.push('PIELE_API_URL must use https');
  if (problems.length) {
    console.error(`Invalid production environment: ${problems.join('; ')}`);
    process.exit(1);
  }
}

const environment = {
  apiUrl: process.env.PIELE_API_URL.replace(/\/+$/, ''),
  supabaseUrl: process.env.PIELE_SUPABASE_URL,
  supabasePublishableKey: process.env.PIELE_SUPABASE_PUBLISHABLE_KEY,
  sampleLeagueData: process.env.PIELE_SAMPLE_LEAGUE_DATA === 'true',
};
writeFileSync(
  'src/environments/environment.ts',
  `// Generated by scripts/write-environment.mjs for Vercel (${process.env.VERCEL_ENV}).\n` +
    `export const environment = ${JSON.stringify(environment, null, 2)};\n`,
);
console.log(`Wrote environment for ${process.env.VERCEL_ENV}.`);
